import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { hwpFixture, pdfFixture } from './fixtures.mjs';
const server = spawn(process.execPath, ['dev.mjs'], { env: { ...process.env, PORT: '4184' }, stdio: 'pipe' });
let browser;
try {
  await new Promise((resolve, reject) => { const timer = setTimeout(() => reject(new Error('Server start timeout')), 10000); server.once('error', reject); server.stdout.once('data', () => { clearTimeout(timer); resolve(); }); server.once('exit', code => reject(new Error('Server exited: ' + code))); });
  browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, acceptDownloads: true });
  const errors = [], external = [], postRequests = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', req => { if (!req.url().startsWith('http://127.0.0.1:4184/') && !req.url().startsWith('blob:')) external.push(req.url()); if (req.method() !== 'GET') postRequests.push(req.url()); });
  await page.goto('http://127.0.0.1:4184/');
  await page.getByRole('tab', { name: '텍스트 붙여넣기' }).click();
  await page.selectOption('#purpose', 'SUPPORT'); await page.click('#sample');
  await page.waitForSelector('#results:not([hidden])');
  assert.match(await page.locator('#sections').innerText(), /500,000원/);
  assert.match(await page.locator('#sections').innerText(), /다른 지원금을 받은 기업은 제외/);
  const downloadEvent = page.waitForEvent('download'); await page.click('#download'); const download = await downloadEvent;
  assert.match(await readFile(await download.path(), 'utf8'), /500,000원/);
  await page.screenshot({ path: '/private/tmp/actiondoc-web-desktop.png', fullPage: true });
  // User supplied markup stays text and never runs or contacts an external host.
  await page.fill('#document-text', '요금: 33,000원입니다.\n<script>window.attacked=true</script>\n다만, 신규 신청자는 제외합니다.'); await page.click('#summarize');
  assert.equal(await page.evaluate(() => window.attacked), undefined);
  await page.getByRole('tab', { name: '파일 선택' }).click();
  await page.setInputFiles('#file', { name: '안내.html', mimeType: 'text/html', buffer: Buffer.from('<p>지원 대상: 지역기업</p><script>window.attacked=true</script><img src="https://invalid.example/tracker"><p>지원 금액: 12,000원</p>') });
  await page.click('#summarize'); await page.waitForSelector('#results:not([hidden])');
  assert.match(await page.locator('#source').evaluate(n => n.parentElement.textContent), /본문 전체/);
  assert.equal(await page.evaluate(() => window.attacked), undefined);
  await page.setInputFiles('#file', { name: '공문.hwp', mimeType: 'application/octet-stream', buffer: Buffer.from(hwpFixture()) }); await page.click('#summarize');
  await page.waitForSelector('#results:not([hidden])'); assert.match(await page.locator('#sections').innerText(), /지역 중소기업/);
  await page.setInputFiles('#file', { name: '50pages.pdf', mimeType: 'application/pdf', buffer: pdfFixture(50) }); await page.click('#summarize');
  await page.waitForSelector('#results:not([hidden])'); assert.match(await page.locator('#result-meta').innerText(), /50쪽/);
  await page.setInputFiles('#file', { name: '484pages.pdf', mimeType: 'application/pdf', buffer: pdfFixture(484) });
  await page.fill('#pdf-start','480'); await page.check('#pdf-fast'); await page.click('#summarize');
  await page.waitForSelector('#results:not([hidden])');
  assert.match(await page.locator('#warnings').innerText(), /484쪽 중 원본 480–484쪽/);
  await page.locator('.source-panel summary').click();
  await page.waitForSelector("#source .evidence");
  const excerpt = await page.locator('#source').textContent();
  assert.match(excerpt,/Page 484:/); assert.doesNotMatch(excerpt,/Page 479:/);
  await page.fill('#pdf-start',''); await page.click('#summarize');
  await page.waitForSelector('#results:not([hidden])');
  assert.match(await page.locator('#warnings').innerText(), /전체 484쪽을 읽어/);
  await page.locator('.source-panel summary').click();
  await page.waitForSelector('#source .evidence');
  assert.match(await page.locator('#source').textContent(), /Page 484:/);
  await page.fill('#pdf-start','400'); await page.fill('#pdf-end','484'); await page.click('#summarize');
  await page.waitForSelector("#error:not([hidden])");
  assert.match(await page.locator('#error').innerText(), /1~50쪽/);
  await page.setInputFiles('#file', { name: 'mixed.pdf', mimeType: 'application/pdf', buffer: pdfFixture(2, [2]) }); await page.click('#summarize');
  await page.waitForSelector('#results:not([hidden])'); assert.match(await page.locator('#warnings').innerText(), /읽지 못한 쪽: 2/);
  const sheet = await browser.newPage();
  await sheet.setContent('<canvas width="1000" height="200"></canvas>');
  await sheet.evaluate(() => {
    const c=document.querySelector('canvas').getContext('2d');
    c.fillStyle='white';c.fillRect(0,0,1000,200);
    c.fillStyle='black';c.font='42px sans-serif';
    c.fillText('지원 금액 500,000원',40,70);
    c.fillText('ACTION NOTICE 2027',40,150);
  });
  const scan = await sheet.pdf(); await sheet.close();
  await page.setInputFiles('#file',{name:'scan.pdf',mimeType:'application/pdf',buffer:scan});
  await page.click('#summarize');
  await page.waitForSelector('#results:not([hidden])',{timeout:60000});
  assert.match(await page.locator('#warnings').innerText(),/OCR 인식 쪽: 1/);
  await page.locator('.source-panel summary').click();
  await page.waitForSelector('#source .evidence');
  assert.match(await page.locator('#source').textContent(),/500,000/);
  // Parallel OCR keeps page order, block numbering and per-page warnings.
  const multi = await browser.newPage();
  await multi.setContent('<style>canvas{display:block;break-after:page}</style>'+[1,2,3,4,5].map(()=>'<canvas width="1000" height="200"></canvas>').join(''));
  await multi.evaluate(() => document.querySelectorAll('canvas').forEach((canvas,i)=>{
    const c=canvas.getContext('2d');c.fillStyle='white';c.fillRect(0,0,1000,200);c.fillStyle='black';c.font='48px sans-serif';c.fillText(`SCAN PAGE ${i+1} FEE ${i+1}00,000`,40,120);
  }));
  const multiScan = await multi.pdf(); await multi.close();
  await page.setInputFiles('#file',{name:'multi-scan.pdf',mimeType:'application/pdf',buffer:multiScan});
  await page.click('#summarize');
  await page.waitForSelector('#results:not([hidden])',{timeout:120000});
  assert.match(await page.locator('#warnings').innerText(),/OCR 인식 쪽: 1, 2, 3, 4, 5\./);
  await page.locator('.source-panel summary').click();
  await page.waitForSelector('#source .evidence');
  const multiText = await page.locator('#source').textContent();
  const order = [1,2,3,4,5].map(n => multiText.search(new RegExp(`PAGE\\s*${n}\\b`)));
  assert.ok(order.every((v,i)=>v>=0 && (i===0 || v>order[i-1])), 'OCR pages out of order: '+multiText);
  for (const [i, el] of (await page.locator('#source .location').allTextContents()).entries()) assert.match(el, new RegExp(`· b${i+1}$`));
  // Enough native text: OCR reads only the large image and does not duplicate the page text.
  const mixed = await browser.newPage();
  await mixed.setContent('<p style="font-size:20px">Native notice text: submit the application form by March 20 at the office.</p><canvas width="1200" height="300"></canvas>');
  await mixed.evaluate(() => {
    const c=document.querySelector('canvas'),x=c.getContext('2d');
    x.fillStyle='white';x.fillRect(0,0,1200,300);x.fillStyle='black';x.font='64px sans-serif';x.fillText('IMAGE FEE 700,000',40,180);
    const img=new Image();img.src=c.toDataURL();img.width=600;c.replaceWith(img);
  });
  const mixedPdf = await mixed.pdf(); await mixed.close();
  await page.setInputFiles('#file',{name:'image-text.pdf',mimeType:'application/pdf',buffer:mixedPdf});
  await page.click('#summarize');
  await page.waitForSelector('#results:not([hidden])',{timeout:60000});
  assert.match(await page.locator('#warnings').innerText(),/OCR 인식 쪽: 1/);
  await page.locator('.source-panel summary').click();
  await page.waitForSelector('#source .evidence');
  const mixedSource = await page.locator('#source').textContent();
  assert.match(mixedSource,/700,?000/);
  assert.equal(mixedSource.match(/submit the application/g).length,1);
  await page.setInputFiles('#file',{name:'cancel.pdf',mimeType:'application/pdf',buffer:scan});
  await page.click('#summarize'); await page.click('#cancel');
  await page.waitForSelector('#error:not([hidden])'); assert.match(await page.locator('#error').innerText(),/취소/);
  assert.equal(await page.locator('#cancel').isVisible(), false);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: '/private/tmp/actiondoc-web-mobile.png', fullPage: true });
  assert.deepEqual(errors, []); assert.deepEqual(external, []); assert.deepEqual(postRequests, []);
  console.log('PASS: text/HTML/HWP/PDF, 50 pages and selected pages of a 484-page PDF, mixed PDF warning, image-region OCR, parallel OCR page order, OCR cancel, evidence export, no script execution or external requests, mobile layout');
} finally { if (browser) await browser.close(); server.kill(); }
